func addVoiceNote(t *testing.T, f fixture, sent bool) (uuid.UUID, domain.Message) {
	t.Helper()
	id := uuid.New()
	_, err := f.pool.Exec(f.ctx, `INSERT INTO attachments(attachment_id,workspace_id,uploaded_by,filename,size,mime_type,blob_name,scan_status) VALUES($1,$2,$3,'voice.webm',128,'audio/webm',$4,'unscanned')`, id, f.workspace, f.author, id.String())
	require.NoError(t, err)
	duration := int32(5000)
	require.NoError(t, f.service.LinkPendingAttachment(f.ctx, domain.AttachmentScope{ActorScope: f.scope, ConversationID: f.room}, id, domain.AttachmentMetadata{Kind: "voice-note", DurationMS: &duration}))
	if !sent {
		return id, domain.Message{}
	}
	message, err := f.service.CreateMessage(f.ctx, domain.CreateMessageCommand{Scope: f.scope, ConversationID: f.room, CreationID: uuid.New(), AttachmentIDs: []uuid.UUID{id}})
	require.NoError(t, err)
	return id, message
}

func TestChatVoiceMetadataAndTranscriptionRequireLiveSentAttachment(t *testing.T) {
	f := newFixture(t)
	scope := domain.AttachmentScope{ActorScope: f.scope, ConversationID: f.room}
	pending, _ := addVoiceNote(t, f, false)
	_, err := f.repo.RequestTranscription(f.ctx, scope, pending, false)
	require.ErrorIs(t, err, domain.ErrNotFound, "unsent recording must never incur inference")
	id, message := addVoiceNote(t, f, true)
	require.Len(t, message.Attachments, 1)
	require.Equal(t, "voice-note", message.Attachments[0].Kind)
	require.EqualValues(t, 5000, *message.Attachments[0].DurationMS)
	result, err := f.repo.GetTranscription(f.ctx, scope, id)
	require.NoError(t, err)
	require.Equal(t, "not_requested", result.Status)
	outsider := domain.AttachmentScope{ActorScope: humanScope(t, f.workspace, f.outsider), ConversationID: f.room}
	_, err = f.repo.RequestTranscription(f.ctx, outsider, id, false)
	require.ErrorIs(t, err, domain.ErrNotFound)
	_, err = f.repo.GetTranscription(f.ctx, outsider, id)
	require.ErrorIs(t, err, domain.ErrNotFound)
	_, err = f.repo.RequestTranscription(f.ctx, scope, id, false)
	require.NoError(t, err)
	_, err = f.service.DeleteMessage(f.ctx, domain.DeleteMessageCommand{Scope: f.scope, MessageID: message.ID, Version: message.Version})
	require.NoError(t, err)
	_, err = f.repo.GetTranscription(f.ctx, scope, id)
	require.ErrorIs(t, err, domain.ErrNotFound)
	var count int
	require.NoError(t, f.pool.QueryRow(f.ctx, `SELECT count(*) FROM chat_audio_transcriptions WHERE attachment_id=$1`, id).Scan(&count))
	require.Zero(t, count, "removing the attachment also removes its transcript")
}

func TestChatTranscriptionConcurrentRequestsAndClaimsAreIdempotent(t *testing.T) {
	f := newFixture(t)
	id, _ := addVoiceNote(t, f, true)
	scope := domain.AttachmentScope{ActorScope: f.scope, ConversationID: f.room}
	var group sync.WaitGroup
	errors := make(chan error, 8)
	for range 8 {
		group.Go(func() {
			_, err := f.repo.RequestTranscription(f.ctx, scope, id, false)
			errors <- err
		})
	}
	group.Wait()
	close(errors)
	for err := range errors {
		require.NoError(t, err)
	}
	claims := make(chan []domain.TranscriptionJob, 8)
	claimErrors := make(chan error, 8)
	for range 8 {
		group.Go(func() {
			jobs, err := f.repo.ClaimTranscriptions(f.ctx, 2)
			claims <- jobs
			claimErrors <- err
		})
	}
	group.Wait()
	close(claims)
	close(claimErrors)
	for err := range claimErrors {
		require.NoError(t, err)
	}
	var all []domain.TranscriptionJob
	for jobs := range claims {
		all = append(all, jobs...)
	}
	require.Len(t, all, 1)
	job := all[0]
	audio, err := f.repo.ReadTranscriptionAudio(f.ctx, job)
	require.NoError(t, err)
	require.Equal(t, "audio/webm", audio.MediaType)
	require.NoError(t, f.repo.CompleteTranscription(f.ctx, job, "The meeting is tomorrow.", "test-model"))
	result, err := f.repo.RequestTranscription(f.ctx, scope, id, true)
	require.NoError(t, err)
	require.Equal(t, "ready", result.Status)
	require.Equal(t, "The meeting is tomorrow.", result.Text)
	jobs, err := f.repo.ClaimTranscriptions(f.ctx, 2)
	require.NoError(t, err)
	require.Empty(t, jobs, "ready result is never regenerated by retry or wake-up")
}

func TestChatTranscriptionInterruptedLeaseRequiresExplicitRetryAndRejectsStaleCompletion(t *testing.T) {
	f := newFixture(t)
	id, _ := addVoiceNote(t, f, true)
	scope := domain.AttachmentScope{ActorScope: f.scope, ConversationID: f.room}
	_, err := f.repo.RequestTranscription(f.ctx, scope, id, false)
	require.NoError(t, err)
	jobs, err := f.repo.ClaimTranscriptions(f.ctx, 2)
	require.NoError(t, err)
	require.Len(t, jobs, 1)
	_, err = f.pool.Exec(f.ctx, `UPDATE chat_audio_transcriptions SET leased_until=$2 WHERE attachment_id=$1`, id, time.Now().Add(-time.Minute))
	require.NoError(t, err)
	newJobs, err := f.repo.ClaimTranscriptions(f.ctx, 2)
	require.NoError(t, err)
	require.Empty(t, newJobs)
	result, err := f.repo.RequestTranscription(f.ctx, scope, id, false)
	require.NoError(t, err)
	require.Equal(t, "failed", result.Status)
	require.Equal(t, "interrupted", result.Error)
	result, err = f.repo.RequestTranscription(f.ctx, scope, id, true)
	require.NoError(t, err)
	require.Equal(t, "pending", result.Status)
	newJobs, err = f.repo.ClaimTranscriptions(f.ctx, 2)
	require.NoError(t, err)
	require.Len(t, newJobs, 1)
	require.NotEqual(t, jobs[0].LeaseToken, newJobs[0].LeaseToken)
	require.ErrorIs(t, f.repo.CompleteTranscription(f.ctx, jobs[0], "Stale result", "test-model"), domain.ErrConflict)
	_, err = f.pool.Exec(f.ctx, `DELETE FROM team_members WHERE team_id=$1 AND user_id=$2`, f.team, f.author)
	require.NoError(t, err)
	_, err = f.repo.ReadTranscriptionAudio(f.ctx, newJobs[0])
	require.ErrorIs(t, err, domain.ErrNotFound, "worker rechecks live requester membership")
}

func TestChatUploadedAudioCanBeTranscribedWithoutRecordingMetadata(t *testing.T) {
	f := newFixture(t)
	scope := domain.AttachmentScope{ActorScope: f.scope, ConversationID: f.room}
	id := uuid.New()
	_, err := f.pool.Exec(f.ctx, `INSERT INTO attachments(attachment_id,workspace_id,uploaded_by,filename,size,mime_type,blob_name,scan_status) VALUES($1,$2,$3,'interview.m4a',128,'audio/mp4',$4,'clean')`, id, f.workspace, f.author, id.String())
	require.NoError(t, err)
	require.NoError(t, f.service.LinkPendingAttachment(f.ctx, scope, id))
	_, err = f.repo.RequestTranscription(f.ctx, scope, id, false)
	require.ErrorIs(t, err, domain.ErrNotFound, "selected but unsent audio must not incur inference")
	message, err := f.service.CreateMessage(f.ctx, domain.CreateMessageCommand{Scope: f.scope, ConversationID: f.room, CreationID: uuid.New(), AttachmentIDs: []uuid.UUID{id}})
	require.NoError(t, err)
	require.Len(t, message.Attachments, 1)
	require.Empty(t, message.Attachments[0].Kind)
	require.Nil(t, message.Attachments[0].DurationMS)
	result, err := f.repo.GetTranscription(f.ctx, scope, id)
	require.NoError(t, err)
	require.Equal(t, "not_requested", result.Status)
	result, err = f.repo.RequestTranscription(f.ctx, scope, id, false)
	require.NoError(t, err)
	require.Equal(t, "pending", result.Status)
	jobs, err := f.repo.ClaimTranscriptions(f.ctx, 2)
	require.NoError(t, err)
	require.Len(t, jobs, 1)
	audio, err := f.repo.ReadTranscriptionAudio(f.ctx, jobs[0])
	require.NoError(t, err)
	require.Equal(t, "audio/mp4", audio.MediaType)
	require.NoError(t, f.repo.CompleteTranscription(f.ctx, jobs[0], "An uploaded audio file.", "test-model"))
	result, err = f.repo.GetTranscription(f.ctx, scope, id)
	require.NoError(t, err)
	require.Equal(t, "ready", result.Status)
	require.Equal(t, "An uploaded audio file.", result.Text)
	_, err = f.pool.Exec(f.ctx, `UPDATE attachments SET mime_type='video/mp4' WHERE attachment_id=$1`, id)
	require.NoError(t, err)
	_, err = f.repo.GetTranscription(f.ctx, scope, id)
	require.ErrorIs(t, err, domain.ErrNotFound, "video attachments are not transcription targets")
}
