package mayarepository

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"

	mayadomain "github.com/complexus-tech/projects-api/internal/modules/maya/domain"
	mayasql "github.com/complexus-tech/projects-api/internal/modules/maya/repository/sqlc"
	platformdatabase "github.com/complexus-tech/projects-api/internal/platform/database"
	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"
)

type transactionRunner func(
	context.Context,
	pgx.TxOptions,
	func(mayasql.Querier) error,
) error

// Repo is Maya's typed PostgreSQL persistence boundary. Every query is
// generated by sqlc; transaction ownership stays here so callers cannot split
// domain invariants across independent database operations.
type Repo struct {
	queries           mayasql.Querier
	withinTransaction transactionRunner
}

func New(pool *pgxpool.Pool) *Repo {
	if pool == nil {
		return &Repo{}
	}

	queries := mayasql.New(pool)
	transactor := platformdatabase.NewTransactor(pool)
	return &Repo{
		queries: queries,
		withinTransaction: func(
			ctx context.Context,
			options pgx.TxOptions,
			operation func(mayasql.Querier) error,
		) error {
			return transactor.WithinTransaction(ctx, options, func(tx pgx.Tx) error {
				return operation(queries.WithTx(tx))
			})
		},
	}
}

// newWithQueries keeps repository tests at the generated-query boundary. A
// test that needs transaction behavior can replace withinTransaction directly.
func newWithQueries(queries mayasql.Querier) *Repo {
	return &Repo{
		queries: queries,
		withinTransaction: func(
			_ context.Context,
			_ pgx.TxOptions,
			operation func(mayasql.Querier) error,
		) error {
			return operation(queries)
		},
	}
}

func (r *Repo) configured() error {
	if r == nil || r.queries == nil || r.withinTransaction == nil {
		return mayadomain.ErrPersistenceNotConfigured
	}
	return nil
}

func (r *Repo) CreateRun(ctx context.Context, input mayadomain.CreateRunInput) (mayadomain.CoreRun, error) {
	if err := r.configured(); err != nil {
		return mayadomain.CoreRun{}, err
	}
	contextPayload := input.Context
	if len(contextPayload) == 0 {
		contextPayload = json.RawMessage(`{}`)
	}

	row, err := r.queries.CreateMayaRun(ctx, mayasql.CreateMayaRunParams{
		WorkspaceID:       input.WorkspaceID,
		StoryID:           input.StoryID,
		TriggeredByUserID: input.TriggeredBy,
		TriggerType:       string(input.Trigger),
		Status:            string(mayadomain.RunStatusRunning),
		ContextPayload:    contextPayload,
	})
	if err != nil {
		return mayadomain.CoreRun{}, fmt.Errorf("create Maya run: %w", err)
	}
	return toCoreRun(row), nil
}

func (r *Repo) CompleteRun(
	ctx context.Context,
	runID uuid.UUID,
	status mayadomain.RunStatus,
	summary string,
	message *string,
) (mayadomain.CoreRun, error) {
	if err := r.configured(); err != nil {
		return mayadomain.CoreRun{}, err
	}
	row, err := r.queries.CompleteMayaRun(ctx, mayasql.CompleteMayaRunParams{
		Status:       string(status),
		Summary:      summary,
		ErrorMessage: message,
		RunID:        runID,
	})
	if err != nil {
		return mayadomain.CoreRun{}, fmt.Errorf("complete Maya run: %w", err)
	}
	return toCoreRun(row), nil
}

func (r *Repo) CreateActions(ctx context.Context, actions []mayadomain.CoreAction) ([]mayadomain.CoreAction, error) {
	if len(actions) == 0 {
		return []mayadomain.CoreAction{}, nil
	}
	if err := r.configured(); err != nil {
		return nil, err
	}

	created := make([]mayadomain.CoreAction, 0, len(actions))
	err := r.withinTransaction(ctx, pgx.TxOptions{}, func(queries mayasql.Querier) error {
		for _, action := range actions {
			payload, err := json.Marshal(action.Payload)
			if err != nil {
				return fmt.Errorf("marshal Maya action payload: %w", err)
			}
			row, err := queries.CreateMayaAction(ctx, mayasql.CreateMayaActionParams{
				RunID:       action.RunID,
				WorkspaceID: action.WorkspaceID,
				StoryID:     action.StoryID,
				ActionType:  string(action.Type),
				Status:      string(action.Status),
				Reason:      action.Reason,
				Payload:     payload,
			})
			if err != nil {
				return fmt.Errorf("create Maya action: %w", err)
			}
			core, err := toCoreAction(row)
			if err != nil {
				return fmt.Errorf("decode Maya action payload: %w", err)
			}
			created = append(created, core)
		}
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("create Maya actions transaction: %w", err)
	}
	return created, nil
}

func (r *Repo) GetWorkPlan(
	ctx context.Context,
	runID, workspaceID, triggeredBy uuid.UUID,
) (mayadomain.WorkPlan, error) {
	if err := r.configured(); err != nil {
		return mayadomain.WorkPlan{}, err
	}
	runRow, err := r.queries.GetMayaWorkPlanRun(ctx, mayasql.GetMayaWorkPlanRunParams{
		RunID:             runID,
		WorkspaceID:       workspaceID,
		TriggeredByUserID: triggeredBy,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return mayadomain.WorkPlan{}, mayadomain.ErrPlanNotFound
	}
	if err != nil {
		return mayadomain.WorkPlan{}, fmt.Errorf("get Maya work plan run: %w", err)
	}

	actionRows, err := r.queries.ListMayaWorkPlanActions(ctx, mayasql.ListMayaWorkPlanActionsParams{
		RunID:       runID,
		WorkspaceID: workspaceID,
		StoryID:     runRow.StoryID,
	})
	if err != nil {
		return mayadomain.WorkPlan{}, fmt.Errorf("get Maya work plan actions: %w", err)
	}
	actions := make([]mayadomain.CoreAction, 0, len(actionRows))
	for _, row := range actionRows {
		action, err := toCoreAction(row)
		if err != nil {
			return mayadomain.WorkPlan{}, fmt.Errorf("decode Maya work plan action: %w", err)
		}
		actions = append(actions, action)
	}
	return mayadomain.WorkPlan{Run: toCoreRun(runRow), Actions: actions}, nil
}

func (r *Repo) MarkActionApplied(ctx context.Context, actionID uuid.UUID) error {
	if err := r.configured(); err != nil {
		return err
	}
	rows, err := r.queries.MarkMayaActionApplied(ctx, mayasql.MarkMayaActionAppliedParams{ActionID: actionID})
	if err != nil {
		return fmt.Errorf("mark Maya action applied: %w", err)
	}
	if rows != 1 {
		return mayadomain.ErrActionNotProposed
	}
	return nil
}

func (r *Repo) MarkActionFailed(ctx context.Context, actionID uuid.UUID, message string) error {
	if err := r.configured(); err != nil {
		return err
	}
	rows, err := r.queries.MarkMayaActionFailed(ctx, mayasql.MarkMayaActionFailedParams{
		ErrorMessage: &message,
		ActionID:     actionID,
	})
	if err != nil {
		return fmt.Errorf("mark Maya action failed: %w", err)
	}
	if rows != 1 {
		return mayadomain.ErrActionNotProposed
	}
	return nil
}
