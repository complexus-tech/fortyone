func TestInspectGoSourceFindsLayerAndPersistenceDebt(t *testing.T) {
	t.Parallel()

	source := []byte(`package service

import (
	"github.com/jmoiron/sqlx"
	linkshttp "github.com/complexus-tech/projects-api/internal/modules/links/http"
	"github.com/complexus-tech/projects-api/internal/modules/stories/repository/sqlc"
	"github.com/complexus-tech/projects-api/pkg/web"
)

const updateStory = ` + "`UPDATE stories SET title = $1 WHERE id = $2`" + `

var _ = sqlx.DB{}
var _ = linkshttp.Config{}
var _ = sqlc.Queries{}
var _ = web.Middleware(nil)
`)

	findings := inspectFixture(t, "internal/modules/stories/service/update.go", source)
	assertRuleCount(t, findings, ruleSQLXImport, 1)
	assertRuleCount(t, findings, ruleDirectSQL, 1)
	assertRuleCount(t, findings, ruleGeneratedSQLCLeak, 1)
	assertRuleCount(t, findings, ruleRepositoryServiceHTTP, 2)
	assertRuleCount(t, findings, ruleCrossModuleHTTPImport, 1)
}

