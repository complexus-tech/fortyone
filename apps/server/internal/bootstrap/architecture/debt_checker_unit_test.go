func TestCompareArchitectureDebtProducesActionableRatchetFailures(t *testing.T) {
	t.Parallel()

	baseline := emptyArchitectureBaseline()
	baseline.RulePathCounts[ruleSQLXImport]["internal/modules/stories/repository/repository.go"] = 1
	baseline.OversizedFiles["internal/modules/stories/service/stories.go"] = 900

	findings := []architectureFinding{
		{Rule: ruleSQLXImport, Path: "internal/modules/stories/repository/new.go", Line: 8, Detail: "imports transitional SQLx package"},
		{Rule: ruleOversizedHandwrittenFile, Path: "internal/modules/stories/service/stories.go", Line: 1, Detail: "handwritten file has 901 lines", Value: 901},
	}
	differences := compareArchitectureDebt(baseline, findings)
	joined := strings.Join(differences, "\n")
	for _, expected := range []string{
		"architecture debt grew for internal/modules/stories/repository/new.go",
		"internal/modules/stories/repository/new.go:8",
		"architecture debt grew for internal/modules/stories/service/stories.go",
		"Split the file by cohesive use case or capability",
		"module:stories",
	} {
		if !strings.Contains(joined, expected) {
			t.Errorf("comparison output does not contain %q:\n%s", expected, joined)
		}
	}
	if strings.Contains(joined, "repository/repository.go") {
		t.Errorf("debt reductions must not fail the gate:\n%s", joined)
	}
}

func TestValidateArchitectureBaselineRejectsIgnoredOrInvalidEntries(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name      string
		mutate    func(architectureBaseline)
		wantError string
	}{
		{
			name: "unknown rule",
			mutate: func(baseline architectureBaseline) {
				baseline.RulePathCounts["typo_rule"] = map[string]int{"internal/example.go": 1}
			},
			wantError: "unknown rule",
		},
		{
			name: "absolute path",
			mutate: func(baseline architectureBaseline) {
				baseline.RulePathCounts[ruleSQLXImport]["/tmp/example.go"] = 1
			},
			wantError: "clean, relative",
		},
		{
			name: "zero count",
			mutate: func(baseline architectureBaseline) {
				baseline.RulePathCounts[ruleSQLXImport]["internal/example.go"] = 0
			},
			wantError: "non-positive count",
		},
		{
			name: "file below gate",
			mutate: func(baseline architectureBaseline) {
				baseline.OversizedFiles["internal/example.go"] = handwrittenFileLineLimit
			},
			wantError: "entries must exceed",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			baseline := emptyArchitectureBaseline()
			test.mutate(baseline)
			err := validateArchitectureBaseline(baseline)
			if err == nil || !strings.Contains(err.Error(), test.wantError) {
				t.Fatalf("validateArchitectureBaseline() error = %v, want error containing %q", err, test.wantError)
			}
		})
	}
}

func TestCountedArchitectureRulesAreUniqueAndActionable(t *testing.T) {
	t.Parallel()

	seen := make(map[string]struct{}, len(countedArchitectureRules))
	previous := ""
	for _, rule := range countedArchitectureRules {
		if _, exists := seen[rule]; exists {
			t.Errorf("architecture rule %q is listed more than once", rule)
		}
		seen[rule] = struct{}{}
		if previous != "" && rule < previous {
			t.Errorf("architecture rules are not sorted: %q appears after %q", rule, previous)
		}
		previous = rule
		if strings.TrimSpace(ruleRemediation[rule]) == "" {
			t.Errorf("architecture rule %q has no remediation guidance", rule)
		}
	}
}

func inspectFixture(t *testing.T, path string, source []byte) []architectureFinding {
	t.Helper()
	findings, err := inspectGoSource(token.NewFileSet(), path, source)
	if err != nil {
		t.Fatalf("inspect fixture %s: %v", path, err)
	}
	return findings
}

func assertRuleCount(t *testing.T, findings []architectureFinding, rule string, want int) {
	t.Helper()
	got := len(findingsForRule(findings, rule))
	if got != want {
		t.Fatalf("rule %s produced %d findings, want %d: %#v", rule, got, want, findings)
	}
}

func findingsForRule(findings []architectureFinding, rule string) []architectureFinding {
	matching := make([]architectureFinding, 0)
	for _, finding := range findings {
		if finding.Rule == rule {
			matching = append(matching, finding)
		}
	}
	return matching
}

func emptyArchitectureBaseline() architectureBaseline {
	baseline := architectureBaseline{
		Version:        architectureBaselineVersion,
		RulePathCounts: make(map[string]map[string]int, len(countedArchitectureRules)),
		OversizedFiles: make(map[string]int),
	}
	for _, rule := range countedArchitectureRules {
		baseline.RulePathCounts[rule] = make(map[string]int)
	}
	return baseline
}
