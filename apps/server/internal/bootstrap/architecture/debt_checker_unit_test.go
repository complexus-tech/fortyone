func TestLooksLikeSQLRejectsProductCopy(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name  string
		value string
		want  bool
	}{
		{name: "select query", value: "SELECT id FROM stories WHERE id = $1", want: true},
		{name: "commented query", value: "-- name: UpdateStory :one\nUPDATE stories SET title = $1", want: true},
		{name: "aliased update", value: "UPDATE stories story SET title = $1", want: true},
		{name: "cte query", value: "WITH candidate AS (SELECT id FROM stories) SELECT id FROM candidate", want: true},
		{name: "recursive cte columns", value: "WITH RECURSIVE tree(id) AS (SELECT id FROM stories) SELECT id FROM tree", want: true},
		{name: "update copy", value: "Update a story, task, or issue", want: false},
		{name: "select copy", value: "Select *Retry remaining* to try again", want: false},
		{name: "error copy", value: "update optimized attachment metadata: %w", want: false},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			if got := looksLikeSQL(test.value); got != test.want {
				t.Fatalf("looksLikeSQL(%q) = %t, want %t", test.value, got, test.want)
			}
		})
	}
}

