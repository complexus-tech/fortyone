const generatedHeader = "// Code generated by sqlc. DO NOT EDIT."

var (
	moduleOutputPattern   = regexp.MustCompile(`^internal/modules/[a-z0-9]+/repository/sqlc$`)
	platformOutputPattern = regexp.MustCompile(`^internal/platform/[a-z0-9]+/repository/sqlc$`)
	approvedInitialisms   = []string{"id", "api", "url", "uri"}
	approvedDatabaseKeys  = map[string]struct{}{
		"managed": {},
		"uri":     {},
	}
	approvedGoKeys = map[string]struct{}{
		"package":                           {},
		"out":                               {},
		"sql_package":                       {},
		"sql_driver":                        {},
		"emit_prepared_queries":             {},
		"emit_interface":                    {},
		"emit_exact_table_names":            {},
		"emit_empty_slices":                 {},
		"emit_pointers_for_null_types":      {},
		"emit_pointers_for_null_enum_types": {},
		"emit_json_tags":                    {},
		"emit_db_tags":                      {},
		"emit_enum_valid_method":            {},
		"omit_unused_structs":               {},
		"query_parameter_limit":             {},
		"initialisms":                       {},
	}
)

type pathList []string

func (p *pathList) UnmarshalYAML(node *yaml.Node) error {
	switch node.Kind {
	case yaml.ScalarNode:
		*p = []string{node.Value}
		return nil
	case yaml.SequenceNode:
		var paths []string
		if err := node.Decode(&paths); err != nil {
			return err
		}
		*p = paths
		return nil
	default:
		return fmt.Errorf("expected a path or path list, got YAML kind %d", node.Kind)
	}
}

type sqlcConfig struct {
	Version   string      `yaml:"version"`
	Overrides yaml.Node   `yaml:"overrides"`
	Plugins   []yaml.Node `yaml:"plugins"`
	SQL       []sqlBlock  `yaml:"sql"`
}

type sqlBlock struct {
	Name                 string               `yaml:"name"`
	Engine               string               `yaml:"engine"`
	Schema               pathList             `yaml:"schema"`
	Queries              pathList             `yaml:"queries"`
	StrictFunctionChecks *bool                `yaml:"strict_function_checks"`
	StrictOrderBy        *bool                `yaml:"strict_order_by"`
	Analyzer             analyzerConfig       `yaml:"analyzer"`
	Database             sqlDatabaseConfig    `yaml:"database"`
	Rules                []string             `yaml:"rules"`
	Gen                  map[string]yaml.Node `yaml:"gen"`
	Codegen              []yaml.Node          `yaml:"codegen"`
}

type analyzerConfig struct {
	Database *bool `yaml:"database"`
}

type sqlDatabaseConfig struct {
	URI     string `yaml:"uri"`
	Managed *bool  `yaml:"managed"`
}

func (c *sqlDatabaseConfig) UnmarshalYAML(node *yaml.Node) error {
	if err := rejectUnknownMappingKeys(node, approvedDatabaseKeys); err != nil {
		return err
	}
	type plainConfig sqlDatabaseConfig
	return node.Decode((*plainConfig)(c))
}

type goGeneratorConfig struct {
	Package                      string   `yaml:"package"`
	Out                          string   `yaml:"out"`
	SQLPackage                   string   `yaml:"sql_package"`
	SQLDriver                    string   `yaml:"sql_driver"`
	EmitPreparedQueries          *bool    `yaml:"emit_prepared_queries"`
	EmitInterface                *bool    `yaml:"emit_interface"`
	EmitExactTableNames          *bool    `yaml:"emit_exact_table_names"`
	EmitEmptySlices              *bool    `yaml:"emit_empty_slices"`
	EmitPointersForNullTypes     *bool    `yaml:"emit_pointers_for_null_types"`
	EmitPointersForNullEnumTypes *bool    `yaml:"emit_pointers_for_null_enum_types"`
	EmitJSONTags                 *bool    `yaml:"emit_json_tags"`
	EmitDBTags                   *bool    `yaml:"emit_db_tags"`
	EmitEnumValidMethod          *bool    `yaml:"emit_enum_valid_method"`
	OmitUnusedStructs            *bool    `yaml:"omit_unused_structs"`
	QueryParameterLimit          *int     `yaml:"query_parameter_limit"`
	Initialisms                  []string `yaml:"initialisms"`
}

type validatedConfig struct {
	inputs  []string
	outputs []string
}

func main() {
	configPath := flag.String("config", "sqlc.yaml", "path to sqlc configuration")
	flag.Parse()
	if flag.NArg() != 1 {
		fail(errors.New("usage: sqlcconfig [-config sqlc.yaml] <validate|inputs|outputs>"))
	}

	validated, err := loadAndValidate(*configPath)
	if err != nil {
		fail(err)
	}

	switch flag.Arg(0) {
	case "validate":
		return
	case "inputs":
		printLines(validated.inputs)
	case "outputs":
		printLines(validated.outputs)
	default:
		fail(fmt.Errorf("unknown command %q", flag.Arg(0)))
	}
}

func loadAndValidate(configPath string) (validatedConfig, error) {
	root, err := filepath.Abs(filepath.Dir(configPath))
	if err != nil {
		return validatedConfig{}, fmt.Errorf("resolve server directory: %w", err)
	}
	rootedFiles, err := os.OpenRoot(root)
	if err != nil {
		return validatedConfig{}, fmt.Errorf("open server directory: %w", err)
	}
	defer rootedFiles.Close()
	contents, err := rootedFiles.ReadFile(filepath.Base(configPath))
	if err != nil {
		return validatedConfig{}, fmt.Errorf("read sqlc config: %w", err)
	}

	var config sqlcConfig
	decoder := yaml.NewDecoder(bytes.NewReader(contents))
	decoder.KnownFields(true)
	if err := decoder.Decode(&config); err != nil {
		return validatedConfig{}, fmt.Errorf("decode sqlc config: %w", err)
	}
	if config.Version != "2" {
		return validatedConfig{}, fmt.Errorf("sqlc config version = %q, want 2", config.Version)
	}
	if len(config.SQL) == 0 {
		return validatedConfig{}, errors.New("sqlc config has no SQL blocks")
	}
	if len(config.Plugins) != 0 {
		return validatedConfig{}, errors.New("sqlc plugins are unsupported; generated output must use the reviewed Go profile")
	}

	names := make(map[string]struct{}, len(config.SQL))
	queryPaths := make(map[string]struct{}, len(config.SQL))
	packages := make(map[string]struct{}, len(config.SQL))
	outputs := make(map[string]struct{}, len(config.SQL))
	inputs := make(map[string]struct{})
	result := validatedConfig{}

	for index, block := range config.SQL {
		label := fmt.Sprintf("sql block %d", index+1)
		if err := requireUnique(label+" name", block.Name, names); err != nil {
			return validatedConfig{}, err
		}
		if len(block.Schema) == 0 || len(block.Queries) == 0 {
			return validatedConfig{}, fmt.Errorf("%s %q must declare schema and query inputs", label, block.Name)
		}
		generator, err := validateGenerationProfile(label, block)
		if err != nil {
			return validatedConfig{}, err
		}
		if err := requireUnique(label+" Go package", generator.Package, packages); err != nil {
			return validatedConfig{}, err
		}

		output, err := validateRelativePath(generator.Out)
		if err != nil {
			return validatedConfig{}, fmt.Errorf("%s %q output: %w", label, block.Name, err)
		}
		if !allowedOutput(output) {
			return validatedConfig{}, fmt.Errorf("%s %q output %q is not an approved generated-only directory", label, block.Name, output)
		}
		if err := requireUnique(label+" output", output, outputs); err != nil {
			return validatedConfig{}, err
		}
		if err := validateOutputDirectory(root, output); err != nil {
			return validatedConfig{}, fmt.Errorf("%s %q: %w", label, block.Name, err)
		}
		result.outputs = append(result.outputs, output)

		for _, schemaPath := range block.Schema {
			path, err := validateInputPath(root, schemaPath)
			if err != nil {
				return validatedConfig{}, fmt.Errorf("%s %q schema: %w", label, block.Name, err)
			}
			if _, exists := inputs[path]; !exists {
				inputs[path] = struct{}{}
				result.inputs = append(result.inputs, path)
			}
		}
		for _, queryPath := range block.Queries {
			path, err := validateInputPath(root, queryPath)
			if err != nil {
				return validatedConfig{}, fmt.Errorf("%s %q queries: %w", label, block.Name, err)
			}
			if err := requireUnique(label+" query path", path, queryPaths); err != nil {
				return validatedConfig{}, err
			}
			if _, exists := inputs[path]; !exists {
				inputs[path] = struct{}{}
				result.inputs = append(result.inputs, path)
			}
		}
	}
	if err := rejectOrphanGeneratedOutputs(root, outputs); err != nil {
		return validatedConfig{}, err
	}

	sort.Strings(result.inputs)
	return result, nil
}

func validateGenerationProfile(label string, block sqlBlock) (goGeneratorConfig, error) {
	if block.Engine != "postgresql" {
		return goGeneratorConfig{}, fmt.Errorf("%s %q engine = %q, want postgresql", label, block.Name, block.Engine)
	}
	if err := requireBool(label+" strict_function_checks", block.StrictFunctionChecks, true); err != nil {
		return goGeneratorConfig{}, err
	}
	if err := requireBool(label+" strict_order_by", block.StrictOrderBy, true); err != nil {
		return goGeneratorConfig{}, err
	}
	if err := requireBool(label+" analyzer.database", block.Analyzer.Database, false); err != nil {
		return goGeneratorConfig{}, err
	}
	if len(block.Codegen) != 0 {
		return goGeneratorConfig{}, fmt.Errorf("%s %q uses unsupported plugin code generation", label, block.Name)
	}
	if len(block.Gen) != 1 {
		return goGeneratorConfig{}, fmt.Errorf("%s %q must declare exactly one Go generator", label, block.Name)
	}

	goNode, ok := block.Gen["go"]
	if !ok {
		return goGeneratorConfig{}, fmt.Errorf("%s %q must use the Go generator", label, block.Name)
	}
	if err := rejectUnknownMappingKeys(&goNode, approvedGoKeys); err != nil {
		return goGeneratorConfig{}, fmt.Errorf("%s %q Go generator: %w", label, block.Name, err)
	}
	var generator goGeneratorConfig
	if err := goNode.Decode(&generator); err != nil {
		return goGeneratorConfig{}, fmt.Errorf("%s %q Go generator: %w", label, block.Name, err)
	}

	if generator.SQLPackage != "pgx/v5" {
		return goGeneratorConfig{}, fmt.Errorf("%s %q sql_package = %q, want pgx/v5", label, block.Name, generator.SQLPackage)
	}
	if generator.SQLDriver != "github.com/jackc/pgx/v5" {
		return goGeneratorConfig{}, fmt.Errorf("%s %q sql_driver = %q, want github.com/jackc/pgx/v5", label, block.Name, generator.SQLDriver)
	}
	boolRequirements := []struct {
		name  string
		value *bool
		want  bool
	}{
		{"emit_prepared_queries", generator.EmitPreparedQueries, false},
		{"emit_interface", generator.EmitInterface, true},
		{"emit_exact_table_names", generator.EmitExactTableNames, false},
		{"emit_empty_slices", generator.EmitEmptySlices, true},
		{"emit_pointers_for_null_types", generator.EmitPointersForNullTypes, true},
		{"emit_pointers_for_null_enum_types", generator.EmitPointersForNullEnumTypes, true},
		{"emit_json_tags", generator.EmitJSONTags, false},
		{"emit_db_tags", generator.EmitDBTags, false},
		{"emit_enum_valid_method", generator.EmitEnumValidMethod, true},
		{"omit_unused_structs", generator.OmitUnusedStructs, true},
	}
	for _, requirement := range boolRequirements {
		if err := requireBool(label+" "+requirement.name, requirement.value, requirement.want); err != nil {
			return goGeneratorConfig{}, err
		}
	}
	if generator.QueryParameterLimit == nil || *generator.QueryParameterLimit != 0 {
		return goGeneratorConfig{}, fmt.Errorf("%s %q query_parameter_limit must be explicitly set to 0", label, block.Name)
	}
	if strings.Join(generator.Initialisms, ",") != strings.Join(approvedInitialisms, ",") {
		return goGeneratorConfig{}, fmt.Errorf(
			"%s %q initialisms = %v, want %v",
			label,
			block.Name,
			generator.Initialisms,
			approvedInitialisms,
		)
	}

	if block.Name == "type-contract" {
		if generator.Package != "contractsql" || generator.Out != "internal/tools/sqlccontract/sqlc" {
			return goGeneratorConfig{}, fmt.Errorf("%s type-contract generator ownership is invalid", label)
		}
		if !equalPaths(block.Schema, "internal/tools/sqlccontract/schema") ||
			!equalPaths(block.Queries, "internal/tools/sqlccontract/queries") {
			return goGeneratorConfig{}, fmt.Errorf("%s type-contract inputs are invalid", label)
		}
		if block.Database.URI != "" || block.Database.Managed != nil || len(block.Rules) != 0 {
			return goGeneratorConfig{}, fmt.Errorf("%s type-contract must remain offline and rule-free", label)
		}
		return generator, nil
	}

	if !moduleOutputPattern.MatchString(generator.Out) && !platformOutputPattern.MatchString(generator.Out) {
		return goGeneratorConfig{}, fmt.Errorf("%s %q output %q is not module-local", label, block.Name, generator.Out)
	}
	moduleRoot := strings.TrimSuffix(generator.Out, "/sqlc")
	if !equalPaths(block.Schema, "internal/migrations") || !equalPaths(block.Queries, moduleRoot+"/queries") {
		return goGeneratorConfig{}, fmt.Errorf("%s %q must use the shared migrations and its module-local queries directory", label, block.Name)
	}
	if !strings.HasSuffix(generator.Package, "sql") {
		return goGeneratorConfig{}, fmt.Errorf("%s %q Go package %q must use an sql suffix", label, block.Name, generator.Package)
	}
	if block.Database.URI != "${SQLC_DATABASE_URL}" {
		return goGeneratorConfig{}, fmt.Errorf("%s %q must use the explicit SQLC_DATABASE_URL", label, block.Name)
	}
	if err := requireBool(label+" database.managed", block.Database.Managed, false); err != nil {
		return goGeneratorConfig{}, err
	}
	if !containsString(block.Rules, "sqlc/db-prepare") {
		return goGeneratorConfig{}, fmt.Errorf("%s %q must enable sqlc/db-prepare", label, block.Name)
	}
	return generator, nil
}

func rejectUnknownMappingKeys(node *yaml.Node, allowed map[string]struct{}) error {
	if node.Kind != yaml.MappingNode {
		return fmt.Errorf("expected a mapping, got YAML kind %d", node.Kind)
	}
	for index := 0; index < len(node.Content); index += 2 {
		key := node.Content[index].Value
		if _, ok := allowed[key]; !ok {
			return fmt.Errorf("unsupported option %q", key)
		}
	}
	return nil
}

func requireBool(label string, value *bool, want bool) error {
	if value == nil {
		return fmt.Errorf("%s must be explicitly set to %t", label, want)
	}
	if *value != want {
		return fmt.Errorf("%s = %t, want %t", label, *value, want)
	}
	return nil
}

func equalPaths(paths pathList, want string) bool {
	return len(paths) == 1 && paths[0] == want
}

func containsString(values []string, want string) bool {
	for _, value := range values {
		if value == want {
			return true
		}
	}
	return false
}

func rejectOrphanGeneratedOutputs(root string, declared map[string]struct{}) error {
	patterns := []string{
		filepath.Join(root, "internal", "modules", "*", "repository", "sqlc"),
		filepath.Join(root, "internal", "platform", "*", "repository", "sqlc"),
		filepath.Join(root, "internal", "tools", "sqlccontract", "sqlc"),
	}
	for _, pattern := range patterns {
		matches, err := filepath.Glob(pattern)
		if err != nil {
			return fmt.Errorf("discover generated sqlc outputs: %w", err)
		}
		for _, match := range matches {
			info, err := os.Stat(match)
			if err != nil {
				return fmt.Errorf("inspect generated sqlc output %q: %w", match, err)
			}
			if !info.IsDir() {
				return fmt.Errorf("generated sqlc output %q is not a directory", match)
			}
			relative, err := filepath.Rel(root, match)
			if err != nil {
				return fmt.Errorf("resolve generated sqlc output %q: %w", match, err)
			}
			relative = filepath.ToSlash(relative)
			if _, ok := declared[relative]; !ok {
				return fmt.Errorf("generated sqlc output %q has no owning sqlc config block", relative)
			}
		}
	}
	return nil
}

func validateInputPath(root, value string) (string, error) {
	path, err := validateRelativePath(value)
	if err != nil {
		return "", err
	}
	if err := rejectSymlinkComponents(root, path); err != nil {
		return "", err
	}
	info, err := os.Stat(filepath.Join(root, filepath.FromSlash(path)))
	if err != nil {
		return "", fmt.Errorf("inspect %q: %w", path, err)
	}
	if !info.Mode().IsRegular() && !info.IsDir() {
		return "", fmt.Errorf("input %q is not a regular file or directory", path)
	}
	return path, nil
}

func validateRelativePath(value string) (string, error) {
	if value == "" {
		return "", errors.New("path is empty")
	}
	if filepath.IsAbs(value) {
		return "", fmt.Errorf("path %q is absolute", value)
	}
	clean := filepath.ToSlash(filepath.Clean(value))
	if clean == "." || clean == ".." || strings.HasPrefix(clean, "../") {
		return "", fmt.Errorf("path %q escapes the server directory", value)
	}
	if clean != filepath.ToSlash(value) {
		return "", fmt.Errorf("path %q is not clean", value)
	}
	return clean, nil
}

func allowedOutput(output string) bool {
	return moduleOutputPattern.MatchString(output) ||
		platformOutputPattern.MatchString(output) ||
		output == "internal/tools/sqlccontract/sqlc"
}

func validateOutputDirectory(root, output string) error {
	if err := rejectSymlinkComponents(root, output); err != nil {
		return fmt.Errorf("unsafe output %q: %w", output, err)
	}
	rootedFiles, err := os.OpenRoot(root)
	if err != nil {
		return fmt.Errorf("open server directory: %w", err)
	}
	defer rootedFiles.Close()
	info, err := rootedFiles.Stat(output)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("inspect output %q: %w", output, err)
	}
	if !info.IsDir() {
		return fmt.Errorf("output %q is not a directory", output)
	}

	rootFS := rootedFiles.FS()
	return fs.WalkDir(rootFS, output, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if path == output {
			return nil
		}
		if entry.Type()&os.ModeSymlink != 0 {
			return fmt.Errorf("output contains symlink %q", path)
		}
		if entry.IsDir() {
			return nil
		}
		if !entry.Type().IsRegular() {
			return fmt.Errorf("output contains non-regular file %q", path)
		}
		contents, err := fs.ReadFile(rootFS, path)
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(contents, []byte(generatedHeader+"\n")) {
			return fmt.Errorf("output contains handwritten or unrecognized file %q", path)
		}
		return nil
	})
}

func rejectSymlinkComponents(root, relative string) error {
	current := root
	for _, component := range strings.Split(filepath.FromSlash(relative), string(filepath.Separator)) {
		current = filepath.Join(current, component)
		info, err := os.Lstat(current)
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		if err != nil {
			return err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("path component %q is a symlink", current)
		}
	}
	return nil
}

func requireUnique(label, value string, seen map[string]struct{}) error {
	if value == "" {
		return fmt.Errorf("%s is empty", label)
	}
	if _, exists := seen[value]; exists {
		return fmt.Errorf("%s %q is duplicated", label, value)
	}
	seen[value] = struct{}{}
	return nil
}

func printLines(lines []string) {
	for _, line := range lines {
		fmt.Println(line)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
