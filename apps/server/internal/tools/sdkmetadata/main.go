// Command sdkmetadata emits the small compatibility metadata shared by the
// generated SDK previews. The bundled OpenAPI document is the only input.
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

type metadata struct {
	OpenAPI string `json:"openapi"`
	Info    struct {
		Version string `json:"version"`
	} `json:"info"`
	Servers []struct {
		URL string `json:"url"`
	} `json:"servers"`
}

type packageManifest struct {
	Version string `json:"version"`
	Private bool   `json:"private"`
}

func main() {
	generatedRootPath := flag.String("generated-root", "", "root containing the bundled contract and generated outputs")
	workspaceRootPath := flag.String("workspace-root", "", "repository workspace root containing the TypeScript package")
	input := flag.String("input", "", "bundled OpenAPI JSON path relative to generated-root")
	goOutput := flag.String("go-output", "", "Go metadata output path relative to generated-root")
	typeScriptOutput := flag.String("typescript-output", "", "TypeScript metadata output path relative to generated-root")
	typeScriptPackage := flag.String("typescript-package", "", "TypeScript package.json path relative to workspace-root")
	flag.Parse()
	if flag.NArg() != 0 || *generatedRootPath == "" || *workspaceRootPath == "" || *input == "" || *goOutput == "" || *typeScriptOutput == "" || *typeScriptPackage == "" {
		fatal(errors.New("usage: sdkmetadata -generated-root <dir> -workspace-root <dir> -input <bundle.json> -go-output <metadata.gen.go> -typescript-output <metadata.ts> -typescript-package <package.json>"))
	}
	generatedRoot, err := os.OpenRoot(*generatedRootPath)
	if err != nil {
		fatal(fmt.Errorf("open generated SDK root: %w", err))
	}
	defer generatedRoot.Close()
	workspaceRoot, err := os.OpenRoot(*workspaceRootPath)
	if err != nil {
		fatal(fmt.Errorf("open SDK workspace root: %w", err))
	}
	defer workspaceRoot.Close()

	contract, err := readMetadata(generatedRoot, *input)
	if err != nil {
		fatal(err)
	}
	if err := validateTypeScriptPackage(workspaceRoot, *typeScriptPackage, contract.Info.Version); err != nil {
		fatal(err)
	}
	if err := writeFile(generatedRoot, *goOutput, renderGo(contract)); err != nil {
		fatal(err)
	}
	if err := writeFile(generatedRoot, *typeScriptOutput, renderTypeScript(contract)); err != nil {
		fatal(err)
	}
}

func validateTypeScriptPackage(root *os.Root, path, contractVersion string) error {
	if root == nil {
		return errors.New("TypeScript SDK package root is required")
	}
	contents, err := root.ReadFile(filepath.Clean(path))
	if err != nil {
		return fmt.Errorf("read TypeScript SDK package: %w", err)
	}
	var manifest packageManifest
	if err := json.Unmarshal(contents, &manifest); err != nil {
		return fmt.Errorf("decode TypeScript SDK package: %w", err)
	}
	if manifest.Version != contractVersion {
		return fmt.Errorf("TypeScript SDK package version %q does not match contract version %q", manifest.Version, contractVersion)
	}
	if !manifest.Private {
		return errors.New("TypeScript SDK preview package must remain private until a release decision is accepted")
	}
	return nil
}

func readMetadata(root *os.Root, path string) (metadata, error) {
	if root == nil {
		return metadata{}, errors.New("bundled OpenAPI root is required")
	}
	contents, err := root.ReadFile(filepath.Clean(path))
	if err != nil {
		return metadata{}, fmt.Errorf("read bundled OpenAPI document: %w", err)
	}
	var contract metadata
	if err := json.Unmarshal(contents, &contract); err != nil {
		return metadata{}, fmt.Errorf("decode bundled OpenAPI document: %w", err)
	}
	if !strings.HasPrefix(contract.OpenAPI, "3.1.") {
		return metadata{}, fmt.Errorf("unsupported OpenAPI version %q: SDK previews require 3.1.x", contract.OpenAPI)
	}
	if strings.TrimSpace(contract.Info.Version) == "" {
		return metadata{}, errors.New("OpenAPI info.version is required for SDK compatibility metadata")
	}
	if len(contract.Servers) == 0 || !safeHTTPSURL(contract.Servers[0].URL) {
		return metadata{}, errors.New("the first OpenAPI server URL must use HTTPS")
	}
	return contract, nil
}

func safeHTTPSURL(raw string) bool {
	parsed, err := url.ParseRequestURI(raw)
	return err == nil && parsed.IsAbs() && parsed.Scheme == "https" && parsed.Host != "" && parsed.User == nil && parsed.RawQuery == "" && parsed.Fragment == ""
}

func renderGo(contract metadata) []byte {
	return []byte(fmt.Sprintf(`// Code generated by internal/tools/sdkmetadata. DO NOT EDIT.
package fortyone

const (
	ContractVersion = %s
	DefaultBaseURL = %s
	OpenAPIVersion = %s
)
`, strconv.Quote(contract.Info.Version), strconv.Quote(contract.Servers[0].URL), strconv.Quote(contract.OpenAPI)))
}

func renderTypeScript(contract metadata) []byte {
	return []byte(fmt.Sprintf(`// Code generated by internal/tools/sdkmetadata. DO NOT EDIT.
export const CONTRACT_VERSION = %s;
export const DEFAULT_BASE_URL = %s;
export const OPENAPI_VERSION = %s;
`, strconv.Quote(contract.Info.Version), strconv.Quote(contract.Servers[0].URL), strconv.Quote(contract.OpenAPI)))
}

func writeFile(root *os.Root, path string, contents []byte) error {
	if root == nil {
		return errors.New("SDK metadata output root is required")
	}
	path = filepath.Clean(path)
	if err := root.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return fmt.Errorf("create SDK metadata directory: %w", err)
	}
	if err := root.WriteFile(path, contents, 0o600); err != nil {
		return fmt.Errorf("write SDK metadata: %w", err)
	}
	return nil
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
