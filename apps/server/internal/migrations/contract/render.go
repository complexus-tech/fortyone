package contract

import (
	"bytes"
	"fmt"
	"strings"
)

// RenderDocumentation renders the human-readable operator contract directly
// from the validated machine-readable manifest.
func RenderDocumentation(manifest Manifest) []byte {
	var output bytes.Buffer
	output.WriteString("# Database migration operations contract\n\n")
	output.WriteString("<!-- Code generated by internal/tools/migrationcheck; DO NOT EDIT. -->\n\n")
	output.WriteString("The machine-readable source of truth is [`internal/migrations/manifest.json`](../../internal/migrations/manifest.json). ")
	fmt.Fprintf(&output, "Versions at or below `%06d` are the established baseline; every later migration must be listed in that manifest exactly once.\n\n", manifest.BaselineVersion)

	output.WriteString("## Policy\n\n")
	output.WriteString("- Applied migrations are immutable. Correct an applied schema with a new migration; never rewrite its SQL.\n")
	output.WriteString("- Every post-baseline migration has both an `up` and `down` file so the chain is testable. A down file does not make a production migration reversible.\n")
	output.WriteString("- `reversible` means the documented down migration preserves the required data and runtime contract. `forward-only` means production recovery is a new forward fix.\n")
	output.WriteString("- Apply migrations in numerical order. Follow each entry's rollout mode before allowing the replacement API or worker to process traffic.\n")
	output.WriteString("- Back up PostgreSQL, record the current migration version, and confirm API/worker readiness before each production rollout. Never use `migrate-force` to bypass a dirty or failed migration without an incident-reviewed repair plan.\n\n")

	output.WriteString("## Inventory\n\n")
	output.WriteString("| Version | Change | Classification | Rollout | API compatibility | Worker compatibility |\n")
	output.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	for _, migration := range manifest.Migrations {
		fmt.Fprintf(
			&output,
			"| `%06d` | `%s` | `%s` | `%s` | %s | %s |\n",
			migration.Version,
			migration.Slug,
			migration.Classification,
			migration.Rollout.Mode,
			markdownTableText(migration.Compatibility.API),
			markdownTableText(migration.Compatibility.Worker),
		)
	}

	for _, migration := range manifest.Migrations {
		fmt.Fprintf(&output, "\n## `%06d_%s`\n\n", migration.Version, migration.Slug)
		fmt.Fprintf(&output, "- **Classification:** `%s`\n", migration.Classification)
		fmt.Fprintf(&output, "- **Files:** `%s`, `%s`\n", migration.Files.Up, migration.Files.Down)
		fmt.Fprintf(&output, "- **Schema:** %s\n", migration.Compatibility.Schema)
		fmt.Fprintf(&output, "- **API:** %s\n", migration.Compatibility.API)
		fmt.Fprintf(&output, "- **Worker:** %s\n", migration.Compatibility.Worker)
		fmt.Fprintf(&output, "- **Mixed versions:** %s\n", migration.Compatibility.MixedVersions)
		fmt.Fprintf(&output, "- **Rollout mode:** `%s`\n\n", migration.Rollout.Mode)

		output.WriteString("Rollout:\n\n")
		writeNumberedList(&output, migration.Rollout.Steps)

		fmt.Fprintf(&output, "\nRecovery (`%s`):\n\n", migration.Recovery.Strategy)
		writeNumberedList(&output, migration.Recovery.Procedure)

		output.WriteString("\nOperational notes:\n\n")
		writeBulletList(&output, migration.OperationalNotes)
	}

	output.WriteString("\n## Adding the next migration\n\n")
	output.WriteString("1. Create one focused migration with `make migrate-create name=lower_snake_case_name`; do not edit an applied migration.\n")
	output.WriteString("2. Add the next contiguous entry to `internal/migrations/manifest.json`, including real mixed-version behavior and a tested recovery procedure.\n")
	output.WriteString("3. Run `make migration-docs` to regenerate this guide, then run `make migration-check`.\n")
	output.WriteString("4. Exercise the full migration chain and relevant integration tests against disposable PostgreSQL before production.\n")

	return output.Bytes()
}

func markdownTableText(value string) string {
	value = strings.ReplaceAll(value, "|", `\|`)
	return strings.Join(strings.Fields(value), " ")
}

func writeNumberedList(output *bytes.Buffer, values []string) {
	for index, value := range values {
		fmt.Fprintf(output, "%d. %s\n", index+1, strings.TrimSpace(value))
	}
}

func writeBulletList(output *bytes.Buffer, values []string) {
	for _, value := range values {
		fmt.Fprintf(output, "- %s\n", strings.TrimSpace(value))
	}
}
